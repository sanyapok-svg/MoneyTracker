-- Синхронизация кошелька при изменении транзакций
create or replace function public.ensure_wallet_row(p_user_id uuid, p_currency text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.wallets (user_id, currency, balance)
  values (p_user_id, p_currency, 0)
  on conflict (user_id, currency) do nothing;
end;
$$;

create or replace function public.apply_wallet_delta(
  p_user_id uuid,
  p_currency text,
  p_delta numeric
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  new_balance numeric;
begin
  perform public.ensure_wallet_row(p_user_id, p_currency);

  update public.wallets
  set balance = balance + p_delta
  where user_id = p_user_id and currency = p_currency
  returning balance into new_balance;

  if new_balance < 0 then
    raise exception 'insufficient_wallet_funds'
      using errcode = 'P0001',
            message = 'Недостаточно средств в кошельке';
  end if;
end;
$$;

create or replace function public.transaction_wallet_delta(
  p_type text,
  p_amount numeric
)
returns numeric
language sql
immutable
as $$
  select case when p_type = 'income' then p_amount else -p_amount end;
$$;

create or replace function public.sync_transaction_wallet()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    perform public.apply_wallet_delta(
      new.user_id,
      new.currency,
      public.transaction_wallet_delta(new.type, new.amount)
    );
    return new;
  elsif tg_op = 'DELETE' then
    perform public.apply_wallet_delta(
      old.user_id,
      old.currency,
      -public.transaction_wallet_delta(old.type, old.amount)
    );
    return old;
  elsif tg_op = 'UPDATE' then
    perform public.apply_wallet_delta(
      old.user_id,
      old.currency,
      -public.transaction_wallet_delta(old.type, old.amount)
    );
    perform public.apply_wallet_delta(
      new.user_id,
      new.currency,
      public.transaction_wallet_delta(new.type, new.amount)
    );
    return new;
  end if;
  return null;
end;
$$;

drop trigger if exists transactions_wallet_sync on public.transactions;
create trigger transactions_wallet_sync
  after insert or update or delete on public.transactions
  for each row
  execute function public.sync_transaction_wallet();

-- Инициализация кошельков из существующих транзакций (только где есть user_id)
insert into public.wallets (user_id, currency, balance)
select
  t.user_id,
  coalesce(t.currency, 'BYN'),
  greatest(
    0,
    coalesce(
      sum(
        case
          when t.type = 'income' then t.amount
          else -t.amount
        end
      ),
      0
    )
  )
from public.transactions t
where t.user_id is not null
group by t.user_id, coalesce(t.currency, 'BYN')
on conflict (user_id, currency) do update
set balance = excluded.balance;
