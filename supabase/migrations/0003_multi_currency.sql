-- === Встроенная миграция 0002 (user_id + RLS), если колонки ещё нет ===
alter table public.transactions
  add column if not exists user_id uuid references auth.users (id) on delete cascade;

delete from public.transactions where user_id is null;

do $$
begin
  if not exists (
    select 1
    from information_schema.columns c
    where c.table_schema = 'public'
      and c.table_name = 'transactions'
      and c.column_name = 'user_id'
      and c.is_nullable = 'YES'
  ) then
    null;
  else
    alter table public.transactions alter column user_id set not null;
  end if;
exception
  when others then
    raise notice 'user_id: %', sqlerrm;
end $$;

create index if not exists transactions_user_id_idx on public.transactions (user_id);
create index if not exists transactions_user_date_idx
  on public.transactions (user_id, date desc);

drop policy if exists "transactions_select_all" on public.transactions;
drop policy if exists "transactions_insert_all" on public.transactions;
drop policy if exists "transactions_update_all" on public.transactions;
drop policy if exists "transactions_delete_all" on public.transactions;

drop policy if exists "transactions_select_own" on public.transactions;
drop policy if exists "transactions_insert_own" on public.transactions;
drop policy if exists "transactions_update_own" on public.transactions;
drop policy if exists "transactions_delete_own" on public.transactions;

create policy "transactions_select_own"
  on public.transactions for select
  using (auth.uid() = user_id);

create policy "transactions_insert_own"
  on public.transactions for insert
  with check (auth.uid() = user_id);

create policy "transactions_update_own"
  on public.transactions for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "transactions_delete_own"
  on public.transactions for delete
  using (auth.uid() = user_id);

-- === Курсы и кошельки (0003) ===

-- Курсы валют (общий кэш, BYN за 1 единицу валюты)
create table if not exists public.exchange_rates (
  currency          text primary key,
  rate_to_byn       numeric(18, 8) not null check (rate_to_byn > 0),
  cur_scale         integer not null default 1 check (cur_scale > 0),
  cur_official_rate numeric(18, 8) not null,
  rate_date         date not null,
  updated_at        timestamptz not null default now()
);

alter table public.exchange_rates enable row level security;

drop policy if exists "exchange_rates_select_authenticated" on public.exchange_rates;
create policy "exchange_rates_select_authenticated"
  on public.exchange_rates for select
  to authenticated
  using (true);

-- Кошельки пользователя
create table if not exists public.wallets (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users (id) on delete cascade,
  currency   text not null,
  balance    numeric(14, 2) not null default 0 check (balance >= 0),
  created_at timestamptz not null default now(),
  unique (user_id, currency),
  check (currency in ('BYN', 'USD', 'EUR', 'RUB', 'KZT'))
);

create index if not exists wallets_user_id_idx on public.wallets (user_id);

alter table public.wallets enable row level security;

drop policy if exists "wallets_select_own" on public.wallets;
drop policy if exists "wallets_insert_own" on public.wallets;
drop policy if exists "wallets_update_own" on public.wallets;

create policy "wallets_select_own"
  on public.wallets for select
  using (auth.uid() = user_id);

create policy "wallets_insert_own"
  on public.wallets for insert
  with check (auth.uid() = user_id);

-- balance меняется только через триггер (security definer), не через клиентский update
create policy "wallets_update_own"
  on public.wallets for update
  using (false);

